#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"
FORGE_BIN="${FORGE_BIN:-$(command -v forge || echo "${HOME}/.foundry/bin/forge")}"

if [[ ! -x "${FORGE_BIN}" ]]; then
  echo "Error: forge binary not found. Install Foundry or set FORGE_BIN." >&2
  exit 1
fi

cd "${REPO_ROOT}"
"${FORGE_BIN}" build --silent

ARTIFACT="${REPO_ROOT}/out/RogueMinerReputation.sol/RogueMinerReputation.json"
if [[ ! -f "${ARTIFACT}" ]]; then
  echo "Error: compiled artifact not found at ${ARTIFACT}" >&2
  exit 1
fi

RUNTIME_HEX="$(python3 -c "import json,sys; d=json.load(open('${ARTIFACT}')); print(d['deployedBytecode']['object'].removeprefix('0x'))")"
if [[ -z "${RUNTIME_HEX}" ]]; then
  echo "Error: empty deployedBytecode in ${ARTIFACT}" >&2
  exit 1
fi

LOCAL_OUT="${REPO_ROOT}/out/rogue_reputation_bytecode.go"
cat > "${LOCAL_OUT}" <<EOF
// Code generated by rogue-chain-contracts/scripts/export-genesis-bytecode.sh. DO NOT EDIT.
package params

import "github.com/ethereum/go-ethereum/common"

// RogueReputationRuntimeBytecode is the compiled EVM runtime bytecode for
// RogueMinerReputation deployed at 0x0000000000000000000000000000000000000020 in Block 0.
var RogueReputationRuntimeBytecode = common.FromHex("${RUNTIME_HEX}")
EOF

echo "Generated local Go bytecode artifact: ${LOCAL_OUT} ($(( ${#RUNTIME_HEX} / 2 )) bytes)"

CORE_DIR="${ROGUE_CORE_CHAIN_DIR:-${REPO_ROOT}/../rogue-core-chain}"
if [[ -d "${CORE_DIR}/params" ]]; then
  TARGET_GO="${CORE_DIR}/params/rogue_reputation_bytecode.go"
  cp "${LOCAL_OUT}" "${TARGET_GO}"
  echo "Synced runtime bytecode directly to: ${TARGET_GO}"
else
  echo "Note: rogue-core-chain not found at ${CORE_DIR}. Copy ${LOCAL_OUT} to <rogue-core-chain>/params/rogue_reputation_bytecode.go"
fi
